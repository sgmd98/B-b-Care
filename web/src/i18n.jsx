const Ctx = createContext(null)

export function FournisseurLangue({ children }) {
  const [langue, setLangue] = useState(
    () => localStorage.getItem('bebecare.langue') || 'fr'
  )
  const valeur = useMemo(() => ({
    langue,
    changer: (l) => { localStorage.setItem('bebecare.langue', l); setLangue(l) },
    t: (cle) => TEXTES[langue]?.[cle] ?? TEXTES.fr[cle] ?? cle,
  }), [langue])
  return <Ctx.Provider value={valeur}>{children}</Ctx.Provider>
}

export const useLangue = () => useContext(Ctx)
export const CLES = Object.keys(TEXTES.fr)
